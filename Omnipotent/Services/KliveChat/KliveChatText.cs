using System.Globalization;
using System.Security.Cryptography;
using System.Text;

namespace Omnipotent.Services.KliveChat
{
    /// <summary>
    /// Hygiene for everything a participant can type (display names, room names, chat) and for the
    /// identifiers the server hands out. Names are one line with control, format and bidi characters
    /// removed, so a name can't break a layout or masquerade as someone else with an RTL override.
    /// </summary>
    public static class KliveChatText
    {
        public const int MaxDisplayNameLength = 32;
        public const int MaxRoomNameLength = 48;
        public const int MaxChatLength = 2000;
        public const int MaxChatLines = 40;

        public static string? CleanDisplayName(string? raw) => CleanLine(raw, MaxDisplayNameLength);

        public static string? CleanRoomName(string? raw) => CleanLine(raw, MaxRoomNameLength);

        /// <summary>One line: whitespace collapsed, invisible characters removed, trimmed and capped. Null when nothing is left.</summary>
        public static string? CleanLine(string? raw, int maxLength)
        {
            if (string.IsNullOrWhiteSpace(raw)) return null;
            var sb = new StringBuilder(Math.Min(raw.Length, maxLength * 2));
            bool pendingSpace = false;
            foreach (char ch in raw.Normalize(NormalizationForm.FormC))
            {
                if (char.IsWhiteSpace(ch))
                {
                    pendingSpace = sb.Length > 0;
                    continue;
                }
                if (IsInvisible(ch, allowJoiners: false)) continue;
                if (pendingSpace)
                {
                    sb.Append(' ');
                    pendingSpace = false;
                }
                sb.Append(ch);
            }
            string cleaned = Truncate(sb.ToString().Trim(), maxLength);
            return cleaned.Length == 0 ? null : cleaned;
        }

        /// <summary>
        /// Chat text: newlines kept (CRLF normalised, at most <see cref="MaxChatLines"/> lines), other
        /// control and bidi characters removed, emoji joiners kept, trimmed and capped. Null when empty.
        /// </summary>
        public static string? CleanChat(string? raw)
        {
            if (string.IsNullOrWhiteSpace(raw)) return null;
            var sb = new StringBuilder(Math.Min(raw.Length, MaxChatLength + 16));
            int lines = 1;
            foreach (char ch in raw.Replace("\r\n", "\n").Replace('\r', '\n').Normalize(NormalizationForm.FormC))
            {
                if (ch == '\n')
                {
                    if (lines >= MaxChatLines) continue;
                    lines++;
                    sb.Append('\n');
                    continue;
                }
                if (ch == '\t')
                {
                    sb.Append(' ');
                    continue;
                }
                if (IsInvisible(ch, allowJoiners: true)) continue;
                sb.Append(ch);
            }
            string cleaned = Truncate(sb.ToString().Trim(), MaxChatLength);
            return cleaned.Length == 0 ? null : cleaned;
        }

        private static bool IsInvisible(char ch, bool allowJoiners)
        {
            // Bidi embeddings, overrides and isolates: the classic way to make text read differently than it is.
            if (ch is >= '‪' and <= '‮' || ch is >= '⁦' and <= '⁩' || ch is '‎' or '‏' or '؜') return true;
            // ZWJ/ZWNJ build emoji sequences and some scripts; harmless inside chat, pointless in a name.
            if (ch is '‌' or '‍') return !allowJoiners;
            return char.GetUnicodeCategory(ch) switch
            {
                UnicodeCategory.Control => true,
                UnicodeCategory.Format => true,
                UnicodeCategory.OtherNotAssigned => true,
                UnicodeCategory.LineSeparator => true,
                UnicodeCategory.ParagraphSeparator => true,
                _ => false,
            };
        }

        /// <summary>Caps by user-perceived characters, so an emoji or a surrogate pair is never cut in half.</summary>
        public static string Truncate(string value, int maxTextElements)
        {
            if (value.Length <= maxTextElements) return value;
            var info = new StringInfo(value);
            return info.LengthInTextElements <= maxTextElements ? value : info.SubstringByTextElements(0, maxTextElements).TrimEnd();
        }

        /// <summary>A participant secret is generated by the browser; 16–128 URL-safe characters.</summary>
        public static bool IsValidSecret(string? secret)
        {
            if (string.IsNullOrEmpty(secret) || secret.Length < 16 || secret.Length > 128) return false;
            foreach (char ch in secret)
            {
                if (!(char.IsAsciiLetterOrDigit(ch) || ch == '-' || ch == '_')) return false;
            }
            return true;
        }

        /// <summary>
        /// A participant's id is derived from the secret its tab holds, so the same tab keeps the same id
        /// across reconnects and server restarts (peers keep their media connections), while nobody can
        /// claim another participant's id without that secret.
        /// </summary>
        public static string ParticipantIdFromSecret(string roomId, string secret)
        {
            byte[] hash = SHA256.HashData(Encoding.UTF8.GetBytes($"{roomId}:{secret}"));
            return Convert.ToHexString(hash, 0, 8).ToLowerInvariant();
        }

        public static string RandomParticipantId() => Convert.ToHexString(RandomNumberGenerator.GetBytes(8)).ToLowerInvariant();

        private const string RoomIdAlphabet = "abcdefghijkmnopqrstuvwxyz23456789";

        /// <summary>Ten characters without look-alikes (no l/1/0): about 50 bits, short enough to read out.</summary>
        public static string NewRoomId()
        {
            Span<char> chars = stackalloc char[10];
            for (int i = 0; i < chars.Length; i++) chars[i] = RoomIdAlphabet[RandomNumberGenerator.GetInt32(RoomIdAlphabet.Length)];
            return new string(chars);
        }

        public static bool IsValidRoomId(string? id)
        {
            if (string.IsNullOrEmpty(id) || id.Length > 32) return false;
            foreach (char ch in id)
            {
                if (!char.IsAsciiLetterOrDigit(ch)) return false;
            }
            return true;
        }
    }
}
